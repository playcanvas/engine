    constructor() {
        super();

        // storage for texture and cubemap asset references
        this._assetReferences = {};

        this._activeParams = new Set();

        this.shaderOptBuilder = new StandardMaterialOptionsBuilder();

        this.reset();
        this._specularIsBlack = isBlack(this._specular);
    }

    reset() {
        // set default values
        Object.keys(_props).forEach((name) => {
            this[`_${name}`] = _props[name].value();
        });

        // typed properties are written to the uniform buffer again; the snapshots of exposed
        // values refer to the replaced objects
        this._mutableProperties?.clear();
        for (const property of _propertyList) {
            this._markPropertyModified(property);
        }

        // the transforms of the previously assigned maps leave the layout
        this._mapTransforms.reset();
        this._markLayoutDirty();
    }

    /** @ignore */
    get propertyDescriptors() {
        // the typed properties, and the transforms of the assigned maps
        return this._mapTransforms.getDescriptors(_propertyList);
    }

