// the anisotropy direction as the cosine and sine of the rotation given in degrees
const convertDegreesToDirection = (degrees, storage, offset) => {
    const radians = degrees * math.DEG_TO_RAD;
    storage[offset] = Math.cos(radians);
    storage[offset + 1] = Math.sin(radians);
};

// the absorption rate of the medium, an attenuation distance of 0 meaning no absorption
const convertToInverse = (distance, storage, offset) => {
    storage[offset] = distance === 0 ? 0 : 1 / distance;
};

// the total height range of the height map in uv units, so the uv offset generated by the parallax
// mapping is at most half of this value in each direction
const convertHeightMapFactor = (factor, storage, offset) => {
    storage[offset] = factor * 0.1;
};

// the dither shader does dAlpha * scale. The dither alpha falls back to the opacity when it was
// never assigned, giving a scale of 1 and the legacy behavior where the dither shares the blend
// alpha. The scale is always stored, so a shader compiled with dither enabled by other means sees
// a safe value rather than an uninitialized one.
const convertAlphaDitherScale = (alphaDither, storage, offset, material) => {
    const opacity = material._opacity;
    storage[offset] = opacity > 0 ? (alphaDither ?? opacity) / opacity : 1;
};

// the corners of the cube map projection box, zero without a box
const convertBoxMin = (box, storage, offset) => {
    const min = box ? box.getMin() : Vec3.ZERO;
    storage[offset] = min.x;
    storage[offset + 1] = min.y;
    storage[offset + 2] = min.z;
};
const convertBoxMax = (box, storage, offset) => {
    const max = box ? box.getMax() : Vec3.ZERO;
    storage[offset] = max.x;
    storage[offset + 1] = max.y;
    storage[offset + 2] = max.z;
};

