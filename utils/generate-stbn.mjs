import { writeFileSync } from 'node:fs';

// Deterministic void-and-cluster construction with XY-plane and temporal-line energy.
// Samples interact only within the same frame or at the same pixel, as in
// https://arxiv.org/abs/2112.09629. No downloaded noise assets are required.
const SIZE = 32;
const FRAMES = 64;
const PLANE = SIZE * SIZE;
const COUNT = PLANE * FRAMES;
const SIGMA = 1.9;
const TEMPORAL_BALANCE = 0.5;
const occupied = new Uint8Array(COUNT);
const energy = new Float64Array(COUNT);
const ranks = new Uint32Array(COUNT);
const spatial = new Float64Array(PLANE);
const temporal = new Float64Array(FRAMES);

for (let y = 0; y < SIZE; y++) {
    for (let x = 0; x < SIZE; x++) {
        const dx = Math.min(x, SIZE - x);
        const dy = Math.min(y, SIZE - y);
        spatial[y * SIZE + x] = Math.exp(-(dx * dx + dy * dy) / (2 * SIGMA * SIGMA));
    }
}
// A constant temporal term penalizes uneven per-pixel sample counts over a whole cycle.
// Local blue-noise energy alone suppresses flicker but can leave grain in stationary averages.
spatial[0] += TEMPORAL_BALANCE;
for (let t = 1; t < FRAMES; t++) {
    const dt = Math.min(t, FRAMES - t);
    temporal[t] = Math.exp(-dt * dt / (2 * SIGMA * SIGMA)) + TEMPORAL_BALANCE;
}

/**
 * @param {number} index - Changed sample.
 * @param {number} sign - Energy change, +1 or -1.
 */
function updateEnergy(index, sign) {
    const pixel = index % PLANE;
    const x = pixel % SIZE;
    const y = Math.floor(pixel / SIZE);
    const frame = Math.floor(index / PLANE);
    const base = frame * PLANE;
    for (let dy = 0; dy < SIZE; dy++) {
        const row = base + ((y + dy) % SIZE) * SIZE;
        for (let dx = 0; dx < SIZE; dx++) {
            energy[row + (x + dx) % SIZE] += sign * spatial[dy * SIZE + dx];
        }
    }
    for (let dt = 1; dt < FRAMES; dt++) {
        energy[((frame + dt) % FRAMES) * PLANE + pixel] += sign * temporal[dt];
    }
}

/**
 * @param {number} value - Occupancy to search.
 * @returns {number} Most clustered occupied sample or emptiest unoccupied sample.
 */
function findSample(value) {
    let best = value ? -Infinity : Infinity;
    let result = -1;
    for (let i = 0; i < COUNT; i++) {
        if (occupied[i] === value && (value ? energy[i] > best : energy[i] < best)) {
            best = energy[i];
            result = i;
        }
    }
    return result;
}

let seed = 0x51ead123;
const initialCount = Math.floor(COUNT / 10);
for (let n = 0; n < initialCount;) {
    seed ^= seed << 13;
    seed ^= seed >>> 17;
    seed ^= seed << 5;
    const index = (seed >>> 0) % COUNT;
    if (!occupied[index]) {
        occupied[index] = 1;
        updateEnergy(index, 1);
        n++;
    }
}

// Relax a sparse initial pattern before assigning its threshold ranks.
for (;;) {
    const cluster = findSample(1);
    occupied[cluster] = 0;
    updateEnergy(cluster, -1);
    const voidIndex = findSample(0);
    occupied[voidIndex] = 1;
    updateEnergy(voidIndex, 1);
    if (cluster === voidIndex) break;
}
const initialPattern = occupied.slice();
const initialEnergy = energy.slice();

for (let rank = initialCount - 1; rank >= 0; rank--) {
    const index = findSample(1);
    ranks[index] = rank;
    occupied[index] = 0;
    updateEnergy(index, -1);
}
occupied.set(initialPattern);
energy.set(initialEnergy);
for (let rank = initialCount; rank < COUNT / 2; rank++) {
    const index = findSample(0);
    ranks[index] = rank;
    occupied[index] = 1;
    updateEnergy(index, 1);
}

// At half density, rank the complement by removing its most clustered samples.
// The energy of a full periodic volume is spatially constant.
const fullEnergy = spatial.reduce((sum, value) => sum + value, 0) + temporal.reduce((sum, value) => sum + value, 0);
for (let i = 0; i < COUNT; i++) {
    occupied[i] = 1 - occupied[i];
    energy[i] = fullEnergy - energy[i];
}
for (let rank = COUNT / 2; rank < COUNT; rank++) {
    const index = findSample(1);
    ranks[index] = rank;
    occupied[index] = 0;
    updateEnergy(index, -1);
}

const data = Uint8Array.from(ranks, rank => Math.floor(rank * 256 / COUNT));
const encoded = Buffer.from(data).toString('base64');
const chunks = encoded.match(/.{1,120}/g);
const source = `// Generated by node utils/generate-stbn.mjs. 32x32x64 scalar spatiotemporal blue noise.
// Void-and-cluster XY-plane / temporal-line energy: https://arxiv.org/abs/2112.09629.
// Includes temporal-cycle density energy to reduce stationary integration error.
const encoded =
${chunks.map(chunk => `    '${chunk}'`).join(' +\n')};

/**
 * Decodes the scalar STBN volume, with X contiguous, then Y, then frame.
 *
 * @returns {Uint8Array} Uniform 8-bit threshold ranks.
 * @ignore
 */
const spatiotemporalBlueNoiseData = () => {
    const binary = atob(encoded);
    const result = new Uint8Array(binary.length);
    for (let i = 0; i < binary.length; i++) result[i] = binary.charCodeAt(i);
    return result;
};

export { spatiotemporalBlueNoiseData };
`;
writeFileSync(new URL('../src/core/math/spatiotemporal-blue-noise.js', import.meta.url), source);
console.log(`Generated ${SIZE}x${SIZE}x${FRAMES} STBN (${data.byteLength} bytes).`);
